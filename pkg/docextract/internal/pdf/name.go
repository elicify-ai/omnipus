// nameToRune maps glyph names to runes (dictEncoder /Differences). The
// table is split across name.go and name_more.go only to keep each file
// under the repository file-size budget.
var nameToRune = mergeNameTables(nameTableA, nameTableB)

func mergeNameTables(tables ...map[string]rune) map[string]rune {
	n := 0
	for _, t := range tables {
		n += len(t)
	}
	m := make(map[string]rune, n)
	for _, t := range tables {
		for k, v := range t {
			m[k] = v
		}
	}
	return m
}

