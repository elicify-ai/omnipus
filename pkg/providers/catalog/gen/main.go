//go:build ignore

// Generator for the provider catalog artifacts.
//
// Invoked via `go generate ./pkg/providers/catalog/...` (the go:generate
// directive is in pkg/providers/catalog/catalog.go).
//
// Outputs (both committed):
//
//	pkg/providers/catalog/data/providers_catalog.json
//	  — the embedded JSON artifact consumed by catalog.LoadCatalog().
//
//	src/lib/generated/providerCatalog.ts
//	  — a TypeScript constant (export const PROVIDER_CATALOG: ProviderCatalogEntry[])
//	    importing the generated TS type.  Consumed by the SPA picker components.
//
// Parity: both outputs are derived from the same catalog.Entries slice so they
// are byte-identical in field values.  TestCatalog_EmbedMatchesGeneratedTS
// in pkg/providers/catalog/catalog_test.go (#13) asserts this at CI time.
//
// Build constraint "ignore" prevents this file from being compiled into the
// binary. It is only run by go generate.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/dapicom-ai/omnipus/pkg/providers/catalog"
)

func main() {
	// Resolve the repo root from this file's location:
	//   .../pkg/providers/catalog/gen/main.go  →  four levels up = repo root
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "gen: runtime.Caller failed")
		os.Exit(1)
	}
	repoRoot := filepath.Join(filepath.Dir(thisFile), "..", "..", "..", "..")

	entries := catalog.Entries
	if len(entries) == 0 {
		fmt.Fprintln(os.Stderr, "gen: refusing to write empty catalog")
		os.Exit(1)
	}

	// ── 1. Emit providers_catalog.json ───────────────────────────────────────
	jsonData, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: marshal catalog entries: %v\n", err)
		os.Exit(1)
	}
	jsonPath := filepath.Join(repoRoot, "pkg", "providers", "catalog", "data", "providers_catalog.json")
	if err := writeFile(jsonPath, append(jsonData, '\n')); err != nil {
		fmt.Fprintf(os.Stderr, "gen: write providers_catalog.json: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("gen: wrote %s (%d entries)\n", jsonPath, len(entries))

	// ── 2. Emit src/lib/generated/providerCatalog.ts ─────────────────────────
	tsPath := filepath.Join(repoRoot, "src", "lib", "generated", "providerCatalog.ts")
	tsContent, err := buildTSContent(entries, jsonData)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: build TS content: %v\n", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(tsPath), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "gen: mkdir %s: %v\n", filepath.Dir(tsPath), err)
		os.Exit(1)
	}
	if err := writeFile(tsPath, []byte(tsContent)); err != nil {
		fmt.Fprintf(os.Stderr, "gen: write providerCatalog.ts: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("gen: wrote %s (%d entries)\n", tsPath, len(entries))
}

// buildTSContent returns the content of the generated TypeScript catalog file.
// The JSON literal embedded in the TS file is produced by marshaling the same
// entries slice as the JSON artifact, ensuring byte-identical field values.
func buildTSContent(entries interface{}, jsonData []byte) (string, error) {
	var sb strings.Builder
	sb.WriteString("// Code generated by go generate ./pkg/providers/catalog/... DO NOT EDIT.\n")
	sb.WriteString("//\n")
	sb.WriteString("// Source of truth: pkg/providers/catalog/catalog.go → Entries\n")
	sb.WriteString("// Regenerate: go generate ./pkg/providers/catalog/...\n")
	sb.WriteString("//\n")
	sb.WriteString("// Parity assertion: TestCatalog_EmbedMatchesGeneratedTS (#13) in\n")
	sb.WriteString("// pkg/providers/catalog/catalog_test.go confirms this file equals the\n")
	sb.WriteString("// embedded providers_catalog.json in field values.\n")
	sb.WriteString("\n")
	sb.WriteString("import type { ProviderCatalogEntry } from '../api/generated/openapi-types'\n")
	sb.WriteString("\n")
	sb.WriteString("// PROVIDER_CATALOG is the curated registry of 23 user-facing LLM provider\n")
	sb.WriteString("// variants. Each entry covers one billable endpoint (company × plan × region).\n")
	sb.WriteString("// Consumed by onboarding ModelKeyStep and Settings ProvidersSection.\n")
	sb.WriteString("// Do NOT hand-edit — regenerate via go generate.\n")
	sb.WriteString("export const PROVIDER_CATALOG: ProviderCatalogEntry[] = ")
	sb.Write(jsonData)
	sb.WriteString("\n")
	return sb.String(), nil
}

// writeFile writes data to path atomically (write temp file then rename).
func writeFile(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", dir, err)
	}
	// Write to a sibling temp file, then rename for atomicity.
	tmp, err := os.CreateTemp(dir, ".gen-catalog-*.tmp")
	if err != nil {
		return fmt.Errorf("create temp: %w", err)
	}
	tmpName := tmp.Name()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return fmt.Errorf("write temp: %w", err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("close temp: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("rename: %w", err)
	}
	return nil
}
