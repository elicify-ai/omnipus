  return {
    session: {
      id: mockSessionId,
      agent_id: 'jim',
      title: 'Fix bug #42',
      type: 'task',
      created_at: '2026-01-01T00:00:00Z',
      updated_at: '2026-01-01T00:00:00Z',
      message_count: 2,
      ...overrides,
    },
    messages: [],
    agent_removed: false,
  }
